  container.addEventListener("click", async function(event) {
    const button = event.target.closest("[data-action]");
    if (!button) return;
    const action = button.dataset.action;
    const id = button.dataset.id;
    if (action === "new-item") openItemForm(null);
    if (action === "open-invite") openInviteDialog();
    if (action === "open-members") openMembersDialog();
    if (action === "close-members") $("#members-dialog").close();
    if (action === "close-invite") $("#invite-dialog").close();
    if (action === "copy-invite") await copyInvitationLink();
    if (action === "confirm-test-account") await confirmInvitedTestAccount();
    if (action === "edit-item") openItemForm(items.find(function(item) { return item.id === id; }));
    if (action === "close-item-form") { $("#pantry-item-form-wrap").hidden = true; editingItem = null; }
    if (action === "restock-item") {
      const item = items.find(function(entry) { return entry.id === id; });
      if (item) openStockDialog(item);
    }
    if (action === "log-consumption") {
      const item = items.find(function(entry) { return entry.id === id; });
      if (item) openLogDialog(item,"consumption");
    }
    if (action === "log-waste") {
      const item = items.find(function(entry) { return entry.id === id; });
      if (item) openLogDialog(item,"waste");
    }
    if (action === "close-log") $("#log-dialog").close();
    if (action === "close-stock") $("#stock-dialog").close();
    if (action === "archive-item") await archiveItem(id);
    if (action === "undo-movement") await undoMovement(id);
    if (action === "refresh") {
      // A full reload re-fetches the signed-in member's role and permission
      // flags in main.js, not only the pantry data in this module.
      window.location.reload();
    }
    if (action === "signout") await onSignOut();
  }, {signal:abortController.signal});

